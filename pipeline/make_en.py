#!/usr/bin/env python3
"""Build en/index.html (the English landing page) from index.html.

The English page is the same app with English meta tags and English "About & FAQ" text,
so Google can show it to people who search in English. Run after every change to index.html:
    python3 pipeline/make_en.py
"""
import os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SEO = os.path.join(ROOT, "pipeline", "seo")


def swap(html, name, new):
    pat = re.compile(r"<!-- seo:%s\b.*?<!-- /seo:%s -->" % (name, name), re.S)
    if len(pat.findall(html)) != 1:
        sys.exit(f"marker seo:{name} not found exactly once in index.html")
    return pat.sub(lambda m: new.strip(), html)


def main():
    html = open(os.path.join(ROOT, "index.html"), encoding="utf-8").read()
    html = html.replace('<html lang="he" dir="rtl">', '<html lang="en" dir="ltr">', 1)
    html = swap(html, "head", open(os.path.join(SEO, "en_head.html"), encoding="utf-8").read())
    html = swap(html, "info", open(os.path.join(SEO, "en_info.html"), encoding="utf-8").read())
    html = html.replace('class="linkish">מידע ושאלות נפוצות</button>', 'class="linkish">About &amp; FAQ</button>', 1)
    html = html.replace("<head>", "<head>\n<!-- GENERATED by pipeline/make_en.py from index.html – do not edit by hand -->", 1)
    os.makedirs(os.path.join(ROOT, "en"), exist_ok=True)
    open(os.path.join(ROOT, "en", "index.html"), "w", encoding="utf-8").write(html)
    print("wrote en/index.html")


if __name__ == "__main__":
    main()
